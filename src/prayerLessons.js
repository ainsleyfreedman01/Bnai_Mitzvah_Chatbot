export const lessons = content.map((lesson, index) => {
    const options = [...lesson.distractors];
    options.splice(index % 3, 0, lesson.answer);
    return { ...lesson, options };
});

export function shuffleOptions(options, random = Math.random) {
    const shuffled = [...options];
    for (let index = shuffled.length - 1; index > 0; index--) {
        const target = Math.floor(random() * (index + 1));
        [shuffled[index], shuffled[target]] = [shuffled[target], shuffled[index]];
    }
    return shuffled;
}

export function findLessons(query, category = null) {
    const search = normalize(query);
    return lessons.filter((lesson) => (!category || lesson.category === category)
        && (!search || [lesson.name, ...lesson.aliases].some((name) => normalize(name).includes(search))));
}
